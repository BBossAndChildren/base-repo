import {readFile, writeFile} from 'node:fs/promises';

const dir=new URL('../src/tokens/',import.meta.url);
const document=JSON.parse(await readFile(new URL('tokens.json',dir),'utf8'));
const flat={};
function flatten(node,path=[]){
  for(const [key,value] of Object.entries(node)){
    const next=[...path,key];
    if(Object.hasOwn(value,'value'))flat[next.join('.')]=value;
    else flatten(value,next);
  }
}
flatten(document.tokens);
const variable=path=>'--ci-'+path.replaceAll('.','-').replace(/[A-Z]/g,letter=>'-'+letter.toLowerCase());
const references=value=>[...String(value).matchAll(/\{([\w.]+)\}/g)].map(match=>match[1]);
const visited=new Set();
function verify(path,stack=[]){
  if(!flat[path])throw Error(`Unknown token reference: ${path}`);
  if(stack.includes(path))throw Error(`Circular token reference: ${[...stack,path].join(' -> ')}`);
  if(visited.has(path))return;
  for(const ref of references(flat[path].value))verify(ref,[...stack,path]);
  visited.add(path);
}
for(const path of Object.keys(flat))verify(path);
if(new Set(Object.keys(flat).map(variable)).size!==Object.keys(flat).length)throw Error('CSS variable name collision');
const cssValue=value=>String(value).replace(/\{([\w.]+)\}/g,(_,path)=>`var(${variable(path)})`);
const declarations=Object.entries(flat).filter(([,token])=>token.runtime!==false).map(([path,token])=>`  ${variable(path)}: ${cssValue(token.value)};`);
await writeFile(new URL('tokens.css',dir),`/* Generated from tokens.json by npm run tokens. */\n.career-intro {\n${declarations.join('\n')}\n}\n`);
let template=await readFile(new URL('CareerIntro.template.css',dir),'utf8');
template=template.replace(/__TOKEN\(([\w.]+)\)__/g,(_,path)=>{
  if(!flat[path])throw Error(`Unknown CSS binding: ${path}`);
  return `var(${variable(path)})`;
}).replaceAll('__COMPACT_BREAKPOINT__',flat['breakpoint.compact'].value);
if(template.includes('__TOKEN('))throw Error('Unresolved CSS binding');
await writeFile(new URL('../CareerIntro.css',dir),'/* Generated from tokens/CareerIntro.template.css. */\n'+template);
const runtime=Object.fromEntries(Object.entries(flat).filter(([,token])=>token.runtime!==false).map(([path])=>[path,variable(path)]));
const helper=`// Generated by npm run tokens. Edit tokens.json, then regenerate.\nexport const tokenVariables=Object.freeze(${JSON.stringify(runtime,null,2)});\nexport function toCSSVariables(overrides={}) {\n  return Object.fromEntries(Object.entries(overrides).map(([path,value])=>{\n    const name=tokenVariables[path];\n    if(!name)throw Error('Unknown or build-only design token: '+path);\n    if(typeof value!=='string' && typeof value!=='number')throw Error('Token override must be CSS text or a number: '+path);\n    return [name,String(value)];\n  }));\n}\n`;
await writeFile(new URL('tokenVariables.js',dir),helper);
await writeFile(new URL('index.js',dir),"export {default as designTokens} from './tokens.json';\nexport {tokenVariables,toCSSVariables} from './tokenVariables.js';\n");
console.log(`Generated ${Object.keys(flat).length} tokens, CSS bindings, and React overrides.`);
