// 디자인 토큰 생성 (docs/design/README.md · 12-decisions.md 결정 26)
// 원본: Unity 담당 토큰 전달물(career-intro-component-tokens-v001)의 생성 스크립트. 검증 규칙(누락 · 순환 참조 · 이름 충돌)은 그대로 두고
// 출력 위치와 범위만 앱에 맞췄다:
//  - tokens.css 를 :root 와 .career-intro 에 함께 선언 (앱 화면도 쓰고, 인트로의 tokens prop 덮어쓰기도 그대로 동작)
//  - 인트로 CSS 는 src/pages/intro/CareerIntro.css 로, 덮어쓰기 표는 TypeScript(tokenVariables.ts)로 만든다
import { readFile, writeFile } from 'node:fs/promises'

const dir = new URL('../src/design/tokens/', import.meta.url)
const introCss = new URL('../src/pages/intro/CareerIntro.css', import.meta.url)
const document = JSON.parse(await readFile(new URL('tokens.json', dir), 'utf8'))
const flat = {}
function flatten(node, path = []) {
  for (const [key, value] of Object.entries(node)) {
    const next = [...path, key]
    if (Object.hasOwn(value, 'value')) flat[next.join('.')] = value
    else flatten(value, next)
  }
}
flatten(document.tokens)
const variable = (path) => '--ci-' + path.replaceAll('.', '-').replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase())
const references = (value) => [...String(value).matchAll(/\{([\w.]+)\}/g)].map((match) => match[1])
const visited = new Set()
function verify(path, stack = []) {
  if (!flat[path]) throw Error(`Unknown token reference: ${path}`)
  if (stack.includes(path)) throw Error(`Circular token reference: ${[...stack, path].join(' -> ')}`)
  if (visited.has(path)) return
  for (const ref of references(flat[path].value)) verify(ref, [...stack, path])
  visited.add(path)
}
for (const path of Object.keys(flat)) verify(path)
if (new Set(Object.keys(flat).map(variable)).size !== Object.keys(flat).length) throw Error('CSS variable name collision')
const cssValue = (value) => String(value).replace(/\{([\w.]+)\}/g, (_, path) => `var(${variable(path)})`)
const runtimeTokens = Object.entries(flat).filter(([, token]) => token.runtime !== false)
const declarations = runtimeTokens.map(([path, token]) => `  ${variable(path)}: ${cssValue(token.value)};`)
await writeFile(new URL('tokens.css', dir), `/* Generated from tokens.json by npm run tokens. 직접 수정하지 않는다. */\n:root,\n.career-intro {\n${declarations.join('\n')}\n}\n`)

let template = await readFile(new URL('CareerIntro.template.css', dir), 'utf8')
template = template
  .replace(/__TOKEN\(([\w.]+)\)__/g, (_, path) => {
    if (!flat[path]) throw Error(`Unknown CSS binding: ${path}`)
    return `var(${variable(path)})`
  })
  .replaceAll('__COMPACT_BREAKPOINT__', flat['breakpoint.compact'].value)
if (template.includes('__TOKEN(')) throw Error('Unresolved CSS binding')
await writeFile(introCss, '/* Generated from src/design/tokens/CareerIntro.template.css by npm run tokens. 직접 수정하지 않는다. */\n' + template)

const runtime = Object.fromEntries(runtimeTokens.map(([path]) => [path, variable(path)]))
const helper = `// Generated by npm run tokens. tokens.json 을 고친 뒤 다시 만든다. 직접 수정하지 않는다.
export const tokenVariables = Object.freeze(${JSON.stringify(runtime, null, 2)} as const)

export type TokenPath = keyof typeof tokenVariables

/** 토큰 경로 → CSS 변수 (인트로 tokens prop 용). 모르는 경로는 오류 */
export function toCSSVariables(overrides: Partial<Record<TokenPath, string | number>> = {}): Record<string, string> {
  return Object.fromEntries(
    Object.entries(overrides).map(([path, value]) => {
      const name = (tokenVariables as Record<string, string>)[path]
      if (!name) throw Error('Unknown or build-only design token: ' + path)
      if (typeof value !== 'string' && typeof value !== 'number') throw Error('Token override must be CSS text or a number: ' + path)
      return [name, String(value)]
    }),
  )
}
`
await writeFile(new URL('tokenVariables.ts', dir), helper)
console.log(`Generated ${Object.keys(flat).length} tokens, CSS bindings, and React overrides.`)
